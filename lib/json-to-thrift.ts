/**
 * JSON → Thrift 转换器。
 *
 * 类型推断规则（PRD §3.3 表格）：
 *   string            → string
 *   integer ≤ 2^31-1  → i32
 *   integer >  2^31-1 → i64
 *   number (含小数)    → double
 *   boolean           → bool
 *   array             → list<T>（T 取首个元素的推断结果）
 *   object            → struct T（嵌套定义，T 名字取自字段名首字母大写）
 *   null              → optional<string>
 */

export interface JsonToThriftOptions {
  namespace: string;
  rootName: string;
  /** 所有字段是否 optional（默认 true，避免 required 缺失值校验失败）。 */
  allOptional?: boolean;
}

interface StructDef {
  name: string;
  fields: Array<{ id: number; type: string; name: string }>;
}

interface ConvertResult {
  /** 推断结果：每个顶层字段 → 推断类型。 */
  inferences: Array<{ name: string; type: string }>;
  thrift: string;
}

const I32_MAX = 0x7fffffff; // 2^31 - 1

/** 推断单个 JSON 值的 Thrift 类型，返回类型字符串（含 list<i32>、MyStruct 等）。 */
function inferType(
  value: unknown,
  fieldName: string,
  registry: Map<string, StructDef>,
): string {
  if (value === null) return "string";

  switch (typeof value) {
    case "string":
      return "string";
    case "boolean":
      return "bool";
    case "number":
      if (Number.isInteger(value)) {
        return Math.abs(value) <= I32_MAX ? "i32" : "i64";
      }
      return "double";
    case "object": {
      if (Array.isArray(value)) {
        if (value.length === 0) return "list<string>";
        const elementType = inferType(value[0], fieldName, registry);
        return `list<${elementType}>`;
      }
      // object → 嵌套 struct
      const structName = capitalize(fieldName) || "SubStruct";
      let def = registry.get(structName);
      if (!def) {
        def = { name: structName, fields: [] };
        registry.set(structName, def);
        collectStructFields(value as object, def, registry);
      }
      return structName;
    }
    default:
      return "string";
  }
}

/** 收集嵌套 object 的字段定义（仅在新 struct 时调用一次）。 */
function collectStructFields(
  obj: object,
  def: StructDef,
  registry: Map<string, StructDef>,
): void {
  let id = 1;
  for (const [key, value] of Object.entries(obj)) {
    const type = inferType(value, key, registry);
    def.fields.push({ id: id++, type, name: key });
  }
}

/** 首字母大写。 */
function capitalize(s: string): string {
  if (!s) return "";
  return s[0]!.toUpperCase() + s.slice(1);
}

/**
 * 推断并生成 Thrift 文本。
 * @param json JSON 对象（已通过 JSON.parse 校验）
 * @param opts 命名空间 + 根结构名 + 是否全 optional
 */
export function jsonToThrift(json: unknown, opts: JsonToThriftOptions): ConvertResult {
  const { namespace, rootName, allOptional = true } = opts;

  if (!namespace || !rootName) {
    throw new Error("namespace 与 rootName 必填");
  }
  if (json === null || typeof json !== "object" || Array.isArray(json)) {
    throw new Error("JSON 顶层必须是 object");
  }

  const registry = new Map<string, StructDef>();
  const root: StructDef = { name: rootName, fields: [] };
  registry.set(rootName, root);

  const inferences: Array<{ name: string; type: string }> = [];
  let id = 1;
  for (const [key, value] of Object.entries(json)) {
    const type = inferType(value, key, registry);
    root.fields.push({ id: id++, type, name: key });
    inferences.push({ name: key, type });
  }

  // 生成 Thrift 文本
  const header = [
    `// Generated by Mock Server · ${new Date().toISOString()}`,
    `// 源 JSON 包含 ${root.fields.length} 个顶层字段、${registry.size - 1} 个嵌套结构`,
    "",
    `namespace java ${namespace}`,
    "",
  ];

  const structBlocks: string[] = [];
  for (const def of registry.values()) {
    const lines = [`struct ${def.name} {`];
    for (const f of def.fields) {
      const opt = allOptional ? "optional " : "";
      lines.push(`  ${f.id}: ${opt}${f.type} ${f.name}`);
    }
    lines.push(`}`);
    structBlocks.push(lines.join("\n"));
  }

  const thrift = header.join("\n") + structBlocks.join("\n\n") + "\n";

  return { inferences, thrift };
}